using CBS.Domain.Common;
using CBS.Domain.Enums;
using CBS.Domain.ValueObjects;

namespace CBS.Domain.SecurityAudit;

public sealed record CtrReportItem(
    string CifNumber,
    string CustomerName,
    int TransactionCount,
    decimal TotalCashAmount,
    string Currency,
    DateTime ReportDate);

public sealed record StrAlertItem(
    string CifNumber,
    string CustomerName,
    StrAlertReason Reason,
    decimal TransactionAmount,
    string Currency,
    string Narrative,
    DateTime DetectedAtUtc);

/// <summary>
/// BFIU AML/CFT Regulatory Reporting Aggregate Root conforming to Bangladesh Bank / BFIU Circular 26
/// and BRPD Circular 12 (Module 11: Regulatory Reporting).
/// Invariants:
/// 1. Cash Transaction Report (CTR) mandatorily aggregates customer cash transactions >= 1,000,000 BDT per day.
/// 2. Suspicious Transaction Report (STR) flags transaction structuring (smurfing) and TP limit breaches.
/// </summary>
public sealed class BfiuRegulatoryReport : AggregateRoot<string>
{
    public string ReportReference => Id;
    public string ReportType { get; private set; } = null!; // "CTR" or "STR"
    public DateTime ReportDate { get; private set; }
    public ComplianceReportStatus Status { get; private set; }
    public IReadOnlyList<CtrReportItem> CtrItems { get; private set; } = [];
    public IReadOnlyList<StrAlertItem> StrAlerts { get; private set; } = [];
    public DateTime GeneratedAtUtc { get; private set; }
    public string GeneratedByUserId { get; private set; } = null!;
    public string BranchCode { get; private set; } = "001";
    public string? GoAmlPayload { get; private set; }
    public string? GoAmlFormat { get; private set; }

    // Parameterless constructor for EF Core ORM materialization
    private BfiuRegulatoryReport() : base(string.Empty) { }

    private BfiuRegulatoryReport(string reportReference) : base(reportReference) { }

    public static BfiuRegulatoryReport GenerateCtr(
        string reportReference,
        DateTime reportDate,
        IEnumerable<(string Cif, string Name, int TxCount, decimal TotalCash)> customerCashAggregates,
        string generatedByUserId,
        string branchCode = "001")
    {
        if (string.IsNullOrWhiteSpace(reportReference))
            throw new ArgumentException("Report reference is required.", nameof(reportReference));
        if (string.IsNullOrWhiteSpace(generatedByUserId))
            throw new ArgumentException("Generated by user ID is required.", nameof(generatedByUserId));

        // BFIU CTR Threshold: Aggregate cash >= 1,000,000 BDT in a single day
        var qualifiedItems = customerCashAggregates
            .Where(c => c.TotalCash >= 1000000m)
            .Select(c => new CtrReportItem(c.Cif, c.Name, c.TxCount, c.TotalCash, "BDT", reportDate.Date))
            .ToList();

        return new BfiuRegulatoryReport(reportReference.Trim())
        {
            ReportType = "CTR",
            ReportDate = reportDate.Date,
            Status = ComplianceReportStatus.Generated,
            CtrItems = qualifiedItems.AsReadOnly(),
            GeneratedAtUtc = DateTime.UtcNow,
            GeneratedByUserId = generatedByUserId.Trim(),
            BranchCode = string.IsNullOrWhiteSpace(branchCode) ? "001" : branchCode.Trim()
        };
    }

    public static BfiuRegulatoryReport GenerateStr(
        string reportReference,
        DateTime reportDate,
        IEnumerable<StrAlertItem> alerts,
        string generatedByUserId,
        string branchCode = "001")
    {
        if (string.IsNullOrWhiteSpace(reportReference))
            throw new ArgumentException("Report reference is required.", nameof(reportReference));
        if (string.IsNullOrWhiteSpace(generatedByUserId))
            throw new ArgumentException("Generated by user ID is required.", nameof(generatedByUserId));

        var alertList = alerts.ToList();

        return new BfiuRegulatoryReport(reportReference.Trim())
        {
            ReportType = "STR",
            ReportDate = reportDate.Date,
            Status = ComplianceReportStatus.Generated,
            StrAlerts = alertList.AsReadOnly(),
            GeneratedAtUtc = DateTime.UtcNow,
            GeneratedByUserId = generatedByUserId.Trim(),
            BranchCode = string.IsNullOrWhiteSpace(branchCode) ? "001" : branchCode.Trim()
        };
    }

    public void SetGoAmlExportPayload(string payload, string format)
    {
        GoAmlPayload = payload;
        GoAmlFormat = format.Trim().ToLowerInvariant();
        Status = ComplianceReportStatus.SubmittedToGoAml;
    }

    public void MarkSubmittedToGoAml()
    {
        Status = ComplianceReportStatus.SubmittedToGoAml;
    }
}
