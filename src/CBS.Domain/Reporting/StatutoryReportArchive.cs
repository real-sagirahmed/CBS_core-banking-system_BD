using System.Security.Cryptography;
using System.Text;
using CBS.Domain.Common;
using CBS.Domain.Enums;
using CBS.Domain.Exceptions;

namespace CBS.Domain.Reporting;

// ARCHITECTURAL INTENT: In compliance with BRPD Circular 12/2024 Clause 11.2.1, statutory regulatory reports
// (SBS-1, SBS-2, SBS-3, RIT, Unclaimed Deposits, Daily Affairs) are legally binding regulatory returns.
// Once generated and archived, the report record is IMMUTABLE:
// 1. Content is hashed via SHA-256 (ContentHash) and stored alongside the serialized JSON/CSV payload.
// 2. Any attempt to modify or delete an archived statutory report throws an InvariantViolationException.
public class StatutoryReportArchive : AggregateRoot<Guid>
{
    public RegulatoryReportType ReportType { get; private set; }
    public DateOnly ReportingCutoffDate { get; private set; }
    public string? BranchId { get; private set; }
    public DateTime GenerationTimestamp { get; private set; }
    public string GeneratedByUserId { get; private set; }
    public ReportExportFormat ExportFormat { get; private set; }
    public string ContentHash { get; private set; }
    public string SerializedPayload { get; private set; }
    public int RecordCount { get; private set; }
    public bool IsSubmitted { get; private set; }
    public string? SubmissionReference { get; private set; }
    public DateTime? SubmissionTimestamp { get; private set; }

    #pragma warning disable CS8618
    protected StatutoryReportArchive() : base(Guid.NewGuid()) { }
    #pragma warning restore CS8618

    private StatutoryReportArchive(
        Guid id,
        RegulatoryReportType reportType,
        DateOnly reportingCutoffDate,
        string? branchId,
        DateTime generationTimestamp,
        string generatedByUserId,
        ReportExportFormat exportFormat,
        string contentHash,
        string serializedPayload,
        int recordCount) : base(id)
    {
        ReportType = reportType;
        ReportingCutoffDate = reportingCutoffDate;
        BranchId = branchId?.Trim();
        GenerationTimestamp = generationTimestamp;
        GeneratedByUserId = generatedByUserId;
        ExportFormat = exportFormat;
        ContentHash = contentHash;
        SerializedPayload = serializedPayload;
        RecordCount = recordCount;
        IsSubmitted = false;
    }

    public static StatutoryReportArchive Create(
        RegulatoryReportType reportType,
        DateOnly reportingCutoffDate,
        string? branchId,
        string generatedByUserId,
        ReportExportFormat exportFormat,
        string serializedPayload,
        int recordCount)
    {
        if (string.IsNullOrWhiteSpace(generatedByUserId))
            throw new ArgumentException("Generated by user ID is required.", nameof(generatedByUserId));

        if (string.IsNullOrWhiteSpace(serializedPayload))
            throw new ArgumentException("Serialized report payload cannot be empty.", nameof(serializedPayload));

        if (recordCount < 0)
            throw new ArgumentException("Record count cannot be negative.", nameof(recordCount));

        string contentHash = ComputeSha256(serializedPayload);

        return new StatutoryReportArchive(
            Guid.NewGuid(),
            reportType,
            reportingCutoffDate,
            branchId,
            DateTime.UtcNow,
            generatedByUserId.Trim(),
            exportFormat,
            contentHash,
            serializedPayload,
            recordCount);
    }

    public void MarkAsSubmitted(string submissionReference, string submittedByUserId)
    {
        if (IsSubmitted)
        {
            throw new InvariantViolationException(
                "DuplicateRegulatorySubmissionInvariant",
                "BRPD Circular 12/2024 (11.2.1)",
                $"Statutory report '{Id}' has already been submitted under reference '{SubmissionReference}'.");
        }

        if (string.IsNullOrWhiteSpace(submissionReference))
            throw new ArgumentException("Submission reference is required.", nameof(submissionReference));

        if (string.IsNullOrWhiteSpace(submittedByUserId))
            throw new ArgumentException("Submitted by user ID is required.", nameof(submittedByUserId));

        IsSubmitted = true;
        SubmissionReference = submissionReference.Trim();
        SubmissionTimestamp = DateTime.UtcNow;
    }

    public bool VerifyIntegrity()
    {
        string expectedHash = ComputeSha256(SerializedPayload);
        return string.Equals(ContentHash, expectedHash, StringComparison.OrdinalIgnoreCase);
    }

    private static string ComputeSha256(string content)
    {
        byte[] bytes = Encoding.UTF8.GetBytes(content);
        byte[] hash = SHA256.HashData(bytes);
        return Convert.ToHexString(hash).ToLowerInvariant();
    }
}
